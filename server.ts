  const proxyMultipart = (gowaPath: string, fields: string[], fileField: string) => async (req: any, res: any) => {
    try {
      const { apiUrl, deviceId, authHeader } = getGoWAHeaders(req.user.uid);
      const { phone, ...rest } = req.body;
      if (!phone || !rest[fileField]) {
        return res.status(400).json({ error: `Missing phone or ${fileField}` });
      }

      const fileBuffer = Buffer.from(rest[fileField], 'base64');
      const mimeMatch = rest[fileField].match(/^data:([^;]+);/);
      const mimeType = mimeMatch ? mimeMatch[1] : 'application/octet-stream';
      const ext = mimeType.split('/')[1] || 'bin';

      const FormData = (await import('form-data')).default;
      const form = new FormData();
      form.append('phone', phone);
      form.append(fileField.replace(/_base64$/, ''), fileBuffer, `file.${ext}`);
      for (const field of fields) {
        if (field !== fileField && rest[field] !== undefined) {
          form.append(field, rest[field]);
        }
      }

      const buffer = form.getBuffer();
      const response = await fetch(`${apiUrl}${gowaPath}`, {
        method: 'POST',
        headers: {
          "Authorization": authHeader,
          "X-Device-Id": deviceId,
          ...form.getHeaders(),
          "Content-Length": String(buffer.length),
        },
        body: buffer
      });
      const data = await response.json();
      res.json(data);
    } catch (err: any) {
      res.status(500).json({ error: err.message });
    }
  };


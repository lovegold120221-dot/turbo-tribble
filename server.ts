      let shouldRegister = stateRes.status === 404;
      if (stateRes.status === 500) {
        const txt = await stateRes.text();
        if (txt.toLowerCase().includes("not found")) shouldRegister = true;
      }
      if (shouldRegister) {
        await fetch(`${apiUrl}/devices`, {
          method: "POST", headers: { "Content-Type": "application/json", "Authorization": authHeader },
          body: JSON.stringify({ device_id: deviceId })
        });
        stateRes = await fetch(`${apiUrl}/devices/${deviceId}/status`, { headers: { "Authorization": authHeader } });
      }
      if (!stateRes.ok) throw new Error(`Device status failed: ${stateRes.status}`);
      const status = await stateRes.json();
      if (status.is_logged_in || status.is_connected || status.results?.is_logged_in || status.results?.is_connected) {
        return res.json({ state: "open", details: status });
      }
      const loginRes = await fetch(`${apiUrl}/app/login?device_id=${deviceId}`, { headers: { "Authorization": authHeader } });
      if (!loginRes.ok) {
        const txt = await loginRes.text();
        if (txt.includes("ALREADY_LOGGED_IN")) return res.json({ state: "open" });
        throw new Error(`QR fetch failed: ${loginRes.status} ${txt}`);
      }
      const json = await loginRes.json();
      res.json({ base64: json.results?.qr_link || json.qr_link || json.qr || "" });
